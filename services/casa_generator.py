"""
CASAScriptGenerator — CASA script generation for Quasar AI
Generates imaging scripts (and, for non-ALMA or explicitly forced cases,
manual calibration scripts) for radio interferometry data reduction.

ALMA reality (skill guardrail 4, products-and-qa.md "Getting a calibrated
MeasurementSet"): ALMA archive data are PIPELINE-calibrated. The delivered
package holds caltables + scripts + QA + selected FITS products but NO
calibrated MeasurementSet; the MS is RESTORED with the package's own
``scriptForPI.py`` under the CASA/pipeline version stated in the QA2 report,
README, weblog or manifest (or obtained from an ARC / NRAO SRDP calibrated-MS
service). A generic manual calibration recipe is the rare exception
(per-EB ``*.scriptForCalibration.py`` for legacy/manual datasets), so for
ALMA this generator refuses to emit one unless ``force_manual=True`` and
instead returns the restore guidance (INT-7, report A-17/A-32).

Registered agent tools:
    - generate_casa_imaging_script(params)
    - generate_casa_calibration_script(params)
"""

